AEGIS_DEFAULT_PROJECT="${AEGIS_DEFAULT_PROJECT:-}"
AEGIS_RPC_ROOT="${AEGIS_RPC_ROOT:-}"
if [ -z "$AEGIS_RPC_ROOT" ] && [ -n "$AEGIS_DEFAULT_PROJECT" ]; then
  AEGIS_RPC_ROOT="$AEGIS_PROJECTS_ROOT/$AEGIS_DEFAULT_PROJECT"
fi
AEGIS_WORKSPACE="${AEGIS_WORKSPACE:-$AEGIS_RPC_ROOT}"
export AGENT_HARNESS_HOME AEGIS_REPO_ROOT AEGIS_PROJECTS_ROOT AEGIS_DEFAULT_PROJECT AEGIS_RPC_ROOT AEGIS_WORKSPACE

if [ -z "${AEGIS_NODE:-}" ]; then
  if command -v node >/dev/null 2>&1; then
    AEGIS_NODE="$(command -v node)"
  else
    AEGIS_NODE=""
  fi
fi
export AEGIS_NODE

AEGIS_TSX="${AEGIS_TSX:-}"
if [ -z "$AEGIS_TSX" ] && [ -n "$AEGIS_NODE" ]; then
  AEGIS_TSX="$(dirname "$AEGIS_NODE")/tsx"
fi
if [ ! -x "$AEGIS_TSX" ] && [ -x "${AGENT_HARNESS_HOME}/tools/real-hermes-mcp/node_modules/.bin/tsx" ]; then
  AEGIS_TSX="${AGENT_HARNESS_HOME}/tools/real-hermes-mcp/node_modules/.bin/tsx"
fi
export AEGIS_TSX

